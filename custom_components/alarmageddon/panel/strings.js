// Deutsch für "de" und "de-*", sonst Englisch ("dev" ist kein Deutsch). Nimmt hass oder ein Objekt mit language.
export function pickLang(hass) {
  const lang = String(hass?.locale?.language || hass?.language || "").toLowerCase();
  return lang === "de" || lang.startsWith("de-") ? "de" : "en";
}

// Text mit Platzhaltern {name}; fehlt ein Schlüssel, steht der Schlüssel selbst (fällt in Tests auf).
export function translate(lang, key, vars = {}) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_m, name) => (vars[name] ?? `{${name}}`));
}
